/**
 * In-code catalogue of the SwanStation libretro core options.
 *
 * This is the single source of truth used by the settings screen, the per-game
 * manager and the in-game menu. Labels and descriptions are the English core
 * fallbacks; localized text is resolved through [SwanStationCoreOptionStrings].
 */
object SwanStationCoreOptions {
    data class Choice(val value: String, val label: String)

    data class Option(
        val key: String,
        val label: String,
        val description: String,
        val category: String,
        val choices: List<Choice>,
        val defaultValue: String,
    ) {
        /** The option's short key without the `swanstation_` prefix. */
        val shortKey: String get() = key.removePrefix("swanstation_")

        /** True for plain on/off options whose only values are `true` and `false`. */
        val isBooleanToggle: Boolean
            get() = choices.map { it.value.lowercase() }.toSet() == setOf("true", "false")
    }

