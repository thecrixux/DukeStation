        "swanstation_CPU_RecompilerICache",
        "swanstation_CDROM_MuteCDAudio",
        "swanstation_Audio_FastHook",
    )

    /** Audio options without a dedicated row of their own (CD-DA has one). */
    private val audioKeys = setOf(
        "swanstation_Audio_FastHook",
    )

    private val unsupportedKeys = setOf(
        "swanstation_Display_ShowOSDMessages",
    )

    /**
     * True when the core option is driven by a dedicated app-level setting
     * (renderer, resolution scale, aspect ratio, crop, ...). Per-game
     * core-option overrides for these keys must be ignored: otherwise a stale
     * core-option entry shadows the app-level value edited by the in-game menu
     * and the game manager.
     */
    fun isManagedKey(key: String): Boolean = key in managedKeys

    fun categories(): List<Category> = categoryList

    fun all(): List<Option> = optionList

    fun forCategory(categoryKey: String): List<Option> = optionList.filter { it.category == categoryKey }

    fun option(key: String): Option? = GooseCoreOptions.option(key) ?: optionsByKey[key]

    fun categoryLabel(categoryKey: String): String =
        categoryList.firstOrNull { it.key == categoryKey }?.label ?: categoryKey

    /** Graphics tab: visual enhancements and display geometry. */
    fun graphicsOptions(): List<Option> =
        (forCategory("enhancement") + forCategory("display"))
            .filterNot { it.key in managedKeys || it.key in unsupportedKeys }

    /** Emulation tab: console behaviour and advanced CPU/CD-ROM settings. */
    fun emulationOptions(): List<Option> =
        (forCategory("console") + forCategory("advanced")).filterNot { it.key in managedKeys }

    /** Controls tab: controller ports and memory cards. */
    fun controlsOptions(): List<Option> =
        forCategory("port").filterNot { it.key in managedKeys || it.isUnsupportedControllerPort() }

    /**
     * The frontend feeds two libretro ports, so controller 3-8 options have no
     * input source and must not be offered in the UI.
     */
    private fun Option.isUnsupportedControllerPort(): Boolean =
        key.startsWith("swanstation_Controller") &&
            key.removePrefix("swanstation_Controller").firstOrNull()?.let { it in '3'..'8' } == true

    /** Audio tab: SPU/CD audio options. */
    fun audioOptions(): List<Option> = optionList.filter { it.key in audioKeys }

    /**
     * Controls section of the in-game menu. Expert lightgun/NeGcon/axis
     * tuning is intentionally not part of this list; it stays available in the
     * app settings and the game manager.
     */
    fun gameMenuControlsOptions(): List<Option> = listOfNotNull(
        option("swanstation_Controller1_ForceAnalog"),
