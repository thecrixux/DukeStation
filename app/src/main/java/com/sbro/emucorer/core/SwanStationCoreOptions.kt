    private val optionList = inheritedOptionList.filter { it.key !in GooseCoreOptions.managedKeys }

    private val optionsByKey: Map<String, Option> by lazy { optionList.associateBy { it.key } }

    /**
     * Keys that already have a dedicated control in the app UI (renderer,
     * resolution, aspect, crop, fast boot, rumble, texture replacements, BIOS
     * selection, memory cards). They must not be rendered again by the generic
     * option rows.
     */
    private val managedKeys = setOf(
        "swanstation_GPU_Renderer",
        "swanstation_GPU_ResolutionScale",
        "swanstation_Display_AspectRatio",
        "swanstation_Display_CropMode",
        "swanstation_BIOS_PatchFastBoot",
